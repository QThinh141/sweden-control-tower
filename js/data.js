/* ---------------------- SMS templates (localized) ------------------- */
function smsText(kind, o, extra) {
  const v = {
    name: o.name.split(' ')[0],
    id: o.id,
    eta: hhmm(o.eta),
    win: hhwin(o.promised[0], o.promised[1]),
    n: extra && extra.n !== undefined ? extra.n : Math.max(1, Math.round(o.eta - o.promised[1])),
  };
  return T('sms' + kind.charAt(0).toUpperCase() + kind.slice(1), v);
}

/* ---------------------- Recommendation engine (ORTEC) -------------- */
function recommendationsFor(o) {
  const route = GEO.routes.find(r => r.id === o.routeId);
  const city = CITY[o.city];
  const alt = route ? route.alt : 'TRK-121';
  const late = o.eta > o.promised[1];
  const dev = Math.round(o.eta - o.promised[1]);
  const recs = [];

  if (!late) {
    const ns = o.promised[1] + 5;
    recs.push({
      kind: 'reslot', icon: '📞', prob: 87,
      title: T('rec1', { win: hhwin(ns, ns + 120) }),
      why: T('rec1Why'),
      impact: [T('impOnTime'), T('imp0km'), T('impSms')],
    });
    recs.push({
      kind: 'reassign', icon: '🚚', prob: 74,
      title: T('rec2', { v: alt, store: city.store }),
      why: T('rec2Why', { v: alt }),
      impact: [T('impOnTime'), T('imp12'), T('imp38')],
    });
    recs.push({
      kind: 'reseq', icon: '🔀', prob: 71,
      title: T('rec3', { district: o.district, route: o.routeId }),
      why: T('rec3Why'),
      impact: [T('imp18'), T('imp1')],
    });
  } else {
    recs.push({
      kind: 'reassign', icon: '🚚', prob: 52,
      title: T('rec4', { v: alt, store: city.store }),
      why: T('rec4Why'),
      impact: [T('imp20', { n: randi(20, 30) }), T('imp41')],
    });
    recs.push({
      kind: 'reslot-nextday', icon: '🎁', prob: 58,
      title: T('rec5'),
      why: T('rec5Why'),
      impact: [T('impNext'), T('imp150'), 'CSAT +'],
    });
    recs.push({
      kind: 'notify', icon: '✉️', prob: 64,
      title: T('rec6', { n: Math.max(30, dev + 18) }),
      why: T('rec6Why'),
      impact: [T('impLate', { n: dev }), 'CSAT +'],
    });
  }
  return recs;
}

